/**
 * Error codes raised by the codec.
 *
 * 0–6 match fflate's FlateErrorCode for the inflate / gzip-header subset we
 * share. 15–17 are wgzip-specific: fflate never verifies trailers or caps
 * decompressed size.
 */
export const GzipErrorCode = {
	UnexpectedEOF: 0,
	InvalidBlockType: 1,
	InvalidLengthLiteral: 2,
	InvalidDistance: 3,
	InvalidHeader: 6,
	ChecksumMismatch: 15,
	SizeMismatch: 16,
	OutputTooLarge: 17,
} as const;

export type GzipErrorCodeValue =
	(typeof GzipErrorCode)[keyof typeof GzipErrorCode];

const messages: Record<number, string> = {
	[GzipErrorCode.UnexpectedEOF]: "unexpected EOF",
	[GzipErrorCode.InvalidBlockType]: "invalid block type",
	[GzipErrorCode.InvalidLengthLiteral]: "invalid length/literal",
	[GzipErrorCode.InvalidDistance]: "invalid distance",
	[GzipErrorCode.InvalidHeader]: "invalid gzip header",
	[GzipErrorCode.ChecksumMismatch]: "CRC32 mismatch",
	// Used for ISIZE trailer mismatch and caller-supplied `out` too small.
	[GzipErrorCode.SizeMismatch]: "size mismatch",
	[GzipErrorCode.OutputTooLarge]: "output exceeds maxSize",
};

/**
 * An error generated by this library.
 *
 * `err.name === "GzipError"` and `instanceof GzipError` are stable.
 * `constructor.name` is not (minified dist mangles class names).
 */
export class GzipError extends Error {
	readonly code: GzipErrorCodeValue;

	constructor(code: GzipErrorCodeValue, message?: string) {
		super(message ?? messages[code] ?? `gzip error ${code}`);
		this.name = "GzipError";
		this.code = code;
	}
}

export function gzipErr(code: GzipErrorCodeValue, message?: string): never {
	throw new GzipError(code, message);
}
